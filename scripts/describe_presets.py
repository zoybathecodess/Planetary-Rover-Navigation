"""Document the distribution-shift levels: writes docs/SHIFT_LEVELS.md from the preset configs (single source of truth)."""
from _common import ROOT  # noqa: F401

import yaml

PRESETS = ["id", "terrain_shift", "sensor_shift", "dynamics_shift", "combined_shift"]
ROWS = [("Terrain: P(normal / sand / rock)", lambda e: f"{e['p_normal']:.2f} / {e['p_sand']:.2f} / {e['p_rock']:.2f}"),
        ("Terrain patch correlation (gen_corr)", lambda e: str(e["gen_corr"])),
        ("Obstacle probability (1 − Σ)", lambda e: f"{1 - e['p_normal'] - e['p_sand'] - e['p_rock']:.2f}"),
        ("Energy per cell (normal / sand / rock)", lambda e: " / ".join(str(v) for v in e["energy_cost"])),
        ("Slip probability (normal / sand / rock)", lambda e: " / ".join(f"{v:.2f}" for v in e["slip_prob"])),
        ("Sensor miss rate", lambda e: f"{e['sensor_miss']:.2f}"), ("Sensor false-detection rate", lambda e: f"{e['sensor_false']:.2f}"),
        ("Sensor reading noise σ", lambda e: f"{e['sensor_sigma']:.2f}"), ("Battery capacity (energy units)", lambda e: str(e["battery"])),
        ("Grid size", lambda e: f"{e['size']}×{e['size']}")]


def render() -> str:
    envs = {p: yaml.safe_load((ROOT / f"configs/sim32_{p}.yaml").read_text())["env"] for p in PRESETS}
    lines = ["# Distribution-shift levels (generated by `scripts/describe_presets.py`; do not edit by hand)", "",
             "Training uses `id` only. The shifted presets change the TRUE simulator parameters; the rover never observes them.", "",
             "| Parameter | " + " | ".join(PRESETS) + " |", "|---|" + "---|" * len(PRESETS)]
    for name, f in ROWS:
        lines.append(f"| {name} | " + " | ".join(f(envs[p]) for p in PRESETS) + " |")
    lines += ["", "## What each preset shifts", "",
              "* **terrain_shift** — rougher world: fewer normal cells, more sand and rock, larger patches, more obstacles (0.15 → 0.18 of cells).",
              "* **sensor_shift** — same world, noisier sensing: 4× miss rate, 4× false-detection rate, 3× reading noise.",
              "* **dynamics_shift** — same world and sensing, but costlier sand/rock (4/6 instead of 3/5) and 2.5–3× slip probability.",
              "* **combined_shift** — all three together (the hardest condition).", "",
              "Within a condition every method is evaluated on the identical list of map seeds (verified by the `run_experiment.py` pairing check). "
              "Across conditions the same seed gives a different terrain whenever the terrain parameters differ; conditions are compared on matched "
              "seed ranges, not on identical terrain."]
    return "\n".join(lines) + "\n"


def main():
    text = render()
    (ROOT / "docs" / "SHIFT_LEVELS.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
